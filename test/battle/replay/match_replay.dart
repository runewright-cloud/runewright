//
// match_replay.dart — a golden-transcript harness for the battle engine.
//
// ## Why this exists
//
// `turn_loop.dart` is ~7.7k lines and mixes deterministic resolution with
// network sequencing and trust validation. Separating those is the highest-
// value refactor available (see the August 2026 architecture review §5), and
// it is also the most dangerous one in the codebase: the failure mode is a
// subtle reordering that silently breaks lockstep determinism, and the only
// tripwire in production is a state-hash mismatch on someone's phone
// mid-match.
//
// This harness is the safety net that makes that refactor routine. It is the
// same discipline `GOLDEN_VECTORS.md` mandates for the circuit, pointed at the
// battle engine: **the corpus is generated by running the current
// implementation, and any change must reproduce it byte-for-byte.**
//
// ## What a transcript records, and why it is hashes rather than state
//
// Serialising the whole `BattleState` would be a large, brittle artifact that
// every new field silently invalidates. It is also unnecessary. What a
// refactor must preserve is the *observable behaviour* of a turn, and
// `BattleState.toCanonicalBytes()` is already the project's definition of
// that — it is what the two devices hash at each other to agree they are still
// in the same match.
//
// So each turn records:
//
//   * the canonical state hash **on both devices** — authoritative. Both,
//     not one, because a refactor that desynced the two would otherwise pass.
//   * a small readable summary (hp, mana, chain, entity counts) — diagnostic
//     only, never authoritative.
//
// The summary is what makes a broken golden useful. A bare hash tells you
// "turn 3 differs" and nothing else; the summary tells you *which field
// moved*, which is usually the whole diagnosis.
//
// ## What it exercises that a single-turn test cannot
//
// Scripts run several turns against the same pair of loops, so they cover the
// state that lives *between* turns and is deliberately excluded from the
// canonical hash — `_drawSchedules`, `_drawSeedNonce`, `_seenPeerCommitments`,
// `_ripplingNonce`, `_componentStartSeat`, and `PendingDelayedSpell`'s
// non-canonical fields. That set is exactly the "latent divergence" the
// architecture review flags in §7: two clients can hold identical canonical
// hashes while differing in secondary state that steers a later turn. A
// multi-turn transcript is the cheapest thing that can catch it.

