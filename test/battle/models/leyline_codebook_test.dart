// ## These are a CROSS-CLIENT CONTRACT
//
// §15: *"Every peer must derive byte-identical codebooks from the same
// configuration."* Two devices that disagree about what `earth-water-fire` means
// under `rivendell 4` resolve different spells from the same certified
// trajectory. So a refactor that changes any pinned literal below is a BREAKING
// CONSENSUS CHANGE requiring a `lexiconVersion` bump, not a test that needs
// updating. If one fails, the change is wrong until proven otherwise.
//
// ## Where the constants came from
//
// **Not from running the code under test.** Every literal here is the output of
// `scripts/gen_leyline_codebook_vectors.py`, a from-scratch second
// implementation written against the byte layout documented in
// `leyline_codebook.dart`'s header rather than transcribed from it. A vector
// generated by the implementation it guards only proves determinism; it cannot
// catch a transcription error, because the error would be in both halves. That
// script also recomputes `leylineConfigHash` independently and reproduces
// `leyline_config_test.dart`'s pinned hashes exactly, which is why the config
// hashes appear here too — they are the derivation's anchor, and a second
// attestation of them is free.
//
// ## Slice B posture
//
// Nothing in production reads a codebook yet. These vectors exist so that the
// day something does (audit Slice D), the bytes are already the ones two
// independent implementations agreed on.

