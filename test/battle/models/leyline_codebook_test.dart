        'communitySeed': 'Rivendell!',
        'mutableMagic': true,
        'formulaLength': 4,
        'noiseDensityPermille': 500,
        'lexiconVersion': 1,
      });
      expect(a, b);
      expect(IncantationCodebook.derive(a).orderedKeys,
          IncantationCodebook.derive(b).orderedKeys);
    });
  });

