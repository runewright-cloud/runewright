      const key = [BorderZone.earth, BorderZone.water, BorderZone.fire];
      final payload = [for (final e in key) leylineKeyElementCode(e)];

      final scores = {
        for (final tag in [
          kLeylineIncantationDomain,
          kLeylineSummonDomain,
          kLeylineArmorDomain,
        ])
          tag: leylineStreamScore(
            domainTag: tag,
            config: config,
            streamTag: kLeylineKeyOrderStream,
            payload: payload,
          ).join(','),
      };
      expect(scores.values.toSet(), hasLength(3),
          reason: 'three tags, three scores');
    });

    test('the two streams of one tag are separated too', () {
      // A one-byte effect-code payload and a one-byte key payload must not be
      // able to share a preimage. They cannot today (the shortest legal key is
      // three elements), but the stream tag is what makes that a property of
      // the encoding rather than of a length bound that may later move.
      final config =
          LeylineConfig.mutable(communitySeed: 'rivendell', formulaLength: 4);
      final asKey = leylineStreamScore(
        domainTag: kLeylineIncantationDomain,
        config: config,
        streamTag: kLeylineKeyOrderStream,
        payload: const [1],
      );
      final asEffect = leylineStreamScore(
        domainTag: kLeylineIncantationDomain,
        config: config,
        streamTag: kLeylineEffectOrderStream,
        payload: const [1],
      );
      expect(asKey, isNot(asEffect));
    });
  });

  // ── The key space (canonical encoding) ───────────────────────────────────

  group('canonical key encoding', () {
    test('the alphabet is the four elements in circuit order, no neutral', () {
      // circuits/GRID_ORDERING_v2.md §Rule indices: 1 Fire, 2 Air, 3 Water,
      // 4 Earth. Neutral's 0 is never a formula element — FormulaTracker
      // commits nothing on a neutral or tied generation — so the tail space is
      // 4^(L-1) exactly as §3 says, not 5^(L-1).
      expect(kLeylineKeyAlphabet, const [
        BorderZone.fire,
        BorderZone.air,
        BorderZone.water,
        BorderZone.earth,
      ]);
      expect(kLeylineKeyAlphabet.map(leylineKeyElementCode), const [1, 2, 3, 4]);
    });

    test('enumeration is lexicographic, most significant element first', () {
      final book = IncantationCodebook.derive(
        LeylineConfig.mutable(communitySeed: 'rivendell', formulaLength: 4),
      );
      expect(book.canonicalKeyAt(0),
          const [BorderZone.fire, BorderZone.fire, BorderZone.fire]);
      expect(book.canonicalKeyAt(1),
          const [BorderZone.fire, BorderZone.fire, BorderZone.air]);
      expect(book.canonicalKeyAt(4),
          const [BorderZone.fire, BorderZone.air, BorderZone.fire]);
      expect(book.canonicalKeyAt(16),
          const [BorderZone.air, BorderZone.fire, BorderZone.fire]);
      expect(book.canonicalKeyAt(63),
          const [BorderZone.earth, BorderZone.earth, BorderZone.earth]);
    });

    test('canonicalKeyIndex and canonicalKeyAt are inverse', () {
      final book = IncantationCodebook.derive(
        LeylineConfig.mutable(communitySeed: 'rivendell', formulaLength: 5),
      );
      for (var i = 0; i < book.totalKeyCount; i++) {
        expect(book.canonicalKeyIndex(book.canonicalKeyAt(i)), i);
      }
    });

    test('effect ORDER is keyed on the pinned code, not on enum order', () {
      // RATIFIED: both places an effect's identity is consulted during
      // derivation use kIncantationEffectCode — the scoring payload and the
      // sort's tiebreak. `EffectKind.values` is only the enumeration source,
      // and the tiebreak is total over sixteen distinct codes, so the input
      // order cannot reach the result. Recompute the whole order from a
      // REVERSED input using only the pinned codes; it must match.
      final config =
          LeylineConfig.mutable(communitySeed: 'rivendell', formulaLength: 4);

      int compare(List<int> a, List<int> b) {
        for (var i = 0; i < a.length && i < b.length; i++) {
          if (a[i] != b[i]) return a[i] < b[i] ? -1 : 1;
        }
        return a.length.compareTo(b.length);
      }

      final reversed = EffectKind.values.reversed.toList();
      final rebuilt = [
        for (final kind in reversed)
          (
            leylineStreamScore(
              domainTag: kLeylineIncantationDomain,
              config: config,
              streamTag: kLeylineEffectOrderStream,
              payload: [incantationEffectCode(kind)],
            ),
            incantationEffectCode(kind),
            kind,
          ),
      ]..sort((a, b) {
          final byScore = compare(a.$1, b.$1);
          return byScore != 0 ? byScore : a.$2.compareTo(b.$2);
        });

      expect([for (final e in rebuilt) e.$3],
          deriveEffectOrder(config),
          reason: 'the effect order must not depend on EffectKind.values order');
    });

    test('the pinned codes equal declaration order TODAY — a coincidence', () {
      // This test exists to fail loudly the day someone reorders `EffectKind`.
      //
      // Right now `incantationEffectCode(kind) == kind.index` for all sixteen,
      // which means a regression that swapped the pinned map for `.index`
      // would change no byte and move no vector — the hazard is real and
      // currently invisible. Reordering the enum is a legitimate cosmetic edit
      // that makes the two diverge; when it happens, this assertion breaks
      // first and sends the reader to `deriveEffectOrder`'s header, where the
      // rule is written: the pinned code is the identity, `.index` is never.
      //
      // Fixing a failure here means updating THIS test, never the derivation
      // and never `kIncantationEffectCode` — the pinned codes are frozen, and
      // the codebook vectors must not move.
      for (final kind in EffectKind.values) {
        expect(incantationEffectCode(kind), kind.index,
            reason: 'if this fails, EffectKind was reordered: leave '
                'kIncantationEffectCode alone, leave the vectors alone, and '
                'delete this assertion');
      }
    });

    test('effect codes are pinned and total', () {
      expect(kIncantationEffectCode, hasLength(16));
      expect(kIncantationEffectCode.values.toSet(),
          List.generate(16, (i) => i).toSet());
      for (final kind in EffectKind.values) {
        expect(incantationEffectCode(kind), isNotNull);
      }
      expect(incantationEffectCode(EffectKind.damage), 0);
      expect(incantationEffectCode(EffectKind.divination), 15);
    });
  });

  // ── The API's guard rails ────────────────────────────────────────────────

  group('guard rails', () {
    test('an ordinary leyline has no derived codebook', () {
      // The one that matters: ordinary play's sixteen tails are the fixed
      // effectKindFromPair table. A caller that forgot to check mutableMagic
      // would otherwise silently rekey every existing spellbook.
      expect(() => IncantationCodebook.derive(LeylineConfig.ordinaryDefault),
          throwsA(isA<LeylineConfigException>()));
      expect(() => IncantationCodebook.derive(LeylineConfig.ordinary('rivendell')),
          throwsA(isA<LeylineConfigException>()));
    });

    test('a wrong-length key is an error, not noise', () {
      final book = IncantationCodebook.derive(
        LeylineConfig.mutable(communitySeed: 'rivendell', formulaLength: 4),
      );
      expect(() => book.lookup(const [BorderZone.fire]), throwsArgumentError);
      expect(
        () => book.lookup(const [
          BorderZone.fire,
          BorderZone.fire,
          BorderZone.fire,
          BorderZone.fire,
        ]),
        throwsArgumentError,
      );
    });

    test('lookup, keysFor and the counts agree', () {
      final book = IncantationCodebook.derive(
        LeylineConfig.mutable(communitySeed: 'rivendell', formulaLength: 4),
      );
      for (final kind in EffectKind.values) {
        final keys = book.keysFor(kind);
        expect(keys, hasLength(book.perEffectKeyCounts[kind]));
        for (final key in keys) {
          expect(book.lookup(key), IncantationEffect(kind));
        }
      }
      expect(
        book.keysFor(EffectKind.damage).length +
            book.keysFor(EffectKind.barrier).length,
        4,
      );
    });

    test('noise is a distinct, exhaustively switchable meaning', () {
      // The representation ruling, exercised: a consumer must be able to
      // distinguish noise from an effect without a null check, and the
      // analyzer must force it to handle both.
      final book = IncantationCodebook.derive(
        LeylineConfig.mutable(communitySeed: 'rivendell', formulaLength: 4),
      );
      var effects = 0;
      var noise = 0;
      for (final key in book.orderedKeys) {
        switch (book.lookup(key)) {
          case IncantationEffect():
            effects++;
          case IncantationNoise():
            noise++;
        }
      }
      expect(effects, 32);
      expect(noise, 32);
      expect(const IncantationNoise(), kIncantationNoise);
      expect(const IncantationEffect(EffectKind.damage),
          const IncantationEffect(EffectKind.damage));
      expect(const IncantationEffect(EffectKind.damage),
          isNot(const IncantationEffect(EffectKind.barrier)));
    });
  });

  // ── Slice B's central claim ──────────────────────────────────────────────

  group('ordinary behaviour is untouched', () {
    test('effectKindFromPair still decides the ordinary table', () {
      // Slice B changes no ordinary semantics. This is the canary: if the
      // fixed table ever starts agreeing with a derived codebook, something
      // has been wired in that should not have been.
      expect(effectKindFromPair(BorderZone.fire, BorderZone.fire),
          EffectKind.damage);
      expect(effectKindFromPair(BorderZone.air, BorderZone.water),
          EffectKind.divination);

      // And the derived codebook is emphatically NOT that table: under
      // `rivendell 4` the tail `fire-fire-fire` is noise, not Blast.
      final book = IncantationCodebook.derive(
        LeylineConfig.mutable(communitySeed: 'rivendell', formulaLength: 4),
      );
      expect(
        book.lookup(const [BorderZone.fire, BorderZone.fire, BorderZone.fire]),
        kIncantationNoise,
      );
    });

    test('the ordinary formula length is still what segmentation uses', () {
      expect(LeylineConfig.ordinaryDefault.formulaLength, 3);
      expect(LeylineConfig.ordinaryDefault.noiseDensityPermille, 0);
    });
  });
