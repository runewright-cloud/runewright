    test('identical inputs under a different tag order differently', () {
      // §8: *"Knowledge of the incantation dictionary must reveal nothing about
      // the summon dictionary."* Summon and Armor key spaces are NOT defined
      // yet (audit R-8); this exercises the primitive over the incantation key
      // space under all three tags purely to prove the separation is real.
