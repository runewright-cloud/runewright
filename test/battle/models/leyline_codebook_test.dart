  // ── Order independence (R-1's whole point) ───────────────────────────────

  group('order independence and determinism', () {
    test('deriving twice gives an identical codebook', () {
      final config =
          LeylineConfig.mutable(communitySeed: 'rivendell', formulaLength: 5);
      final a = IncantationCodebook.derive(config);
      final b = IncantationCodebook.derive(config);
      expect(a.orderedKeys, b.orderedKeys);
      expect(a.effectOrder, b.effectOrder);
      for (final key in a.orderedKeys) {
        expect(a.lookup(key), b.lookup(key));
      }
    });

    test('every key\'s rank is independently computable from its own score', () {
      // THE order-independence evidence. Sort-by-hash was chosen (R-1,
      // candidate B) precisely so that an entry's position depends on nothing
      // but its own score and the scores it is compared against — never on
      // arrival order, insertion order, or a shuffle's internal state. That
      // property is checkable directly: recompute each key's rank as "how many
      // keys sort before me", from scratch, and it must equal the position the
      // derivation put it in.
      final config =
          LeylineConfig.mutable(communitySeed: 'rivendell', formulaLength: 4);
      final book = IncantationCodebook.derive(config);

      List<int> payloadOf(List<BorderZone> key) =>
          [for (final e in key) leylineKeyElementCode(e)];
      int compare(List<int> a, List<int> b) {
        for (var i = 0; i < a.length && i < b.length; i++) {
          if (a[i] != b[i]) return a[i] < b[i] ? -1 : 1;
        }
        return a.length.compareTo(b.length);
      }

      final all = [
        for (var i = 0; i < book.totalKeyCount; i++) book.canonicalKeyAt(i),
      ];
      // Positions keyed by canonical index, not by `indexOf`: Dart's `==` on
      // `List` is identity, so `orderedKeys.indexOf(aFreshlyBuiltKey)` is
      // always -1. The canonical index is the key's identity here.
      final position = <int, int>{
        for (var i = 0; i < book.orderedKeys.length; i++)
          book.canonicalKeyIndex(book.orderedKeys[i]): i,
      };
      for (final key in all) {
        final score = leylineStreamScore(
          domainTag: kLeylineIncantationDomain,
          config: config,
          streamTag: kLeylineKeyOrderStream,
          payload: payloadOf(key),
        );
        var rank = 0;
        for (final other in all) {
          if (identical(other, key)) continue;
          final otherScore = leylineStreamScore(
            domainTag: kLeylineIncantationDomain,
            config: config,
            streamTag: kLeylineKeyOrderStream,
            payload: payloadOf(other),
          );
          final byScore = compare(otherScore, score);
          if (byScore < 0 ||
              (byScore == 0 && compare(payloadOf(other), payloadOf(key)) < 0)) {
            rank++;
          }
        }
        expect(position[book.canonicalKeyIndex(key)], rank,
            reason: 'rank of $key must be computable without the sort');
      }
    });

    test('the derived order is a permutation of the canonical enumeration', () {
      // Not a sample, not a filter: every key appears exactly once. A sort that
      // dropped or duplicated an entry would silently give some tail no meaning
      // at all, which is a different failure from "noise".
      for (final length in [4, 5]) {
        final book = IncantationCodebook.derive(
          LeylineConfig.mutable(communitySeed: 'rivendell', formulaLength: length),
        );
        final seen = book.orderedKeys.map(book.canonicalKeyIndex).toSet();
        expect(seen, hasLength(book.totalKeyCount));
        expect(seen.reduce((a, b) => a > b ? a : b), book.totalKeyCount - 1);
        expect(seen.reduce((a, b) => a < b ? a : b), 0);
      }
    });

    test('an equal config built by a different route derives the same book', () {
      // The construction reads only the config's canonical fields, so two
      // configs that are `==` must be indistinguishable to it.
      final a = LeylineConfig.mutable(
        communitySeed: 'rivendell',
        formulaLength: 4,
        noiseDensityPermille: 500,
      );
