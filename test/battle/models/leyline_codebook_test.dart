/// The per-effect key counts of [book], in `EffectKind` declaration order —
/// the shape `gen_leyline_codebook_vectors.py` prints.
List<int> _countsInDeclarationOrder(IncantationCodebook book) {
  final counts = book.perEffectKeyCounts;
  return [for (final kind in EffectKind.values) counts[kind]!];
}

/// The derived-order noise keys of [book].
List<List<BorderZone>> _noiseKeys(IncantationCodebook book) => [
      for (final key in book.orderedKeys)
        if (book.lookup(key) is IncantationNoise) key,
    ];

/// The meanings of [book]'s first [n] ordered keys.
List<EffectKind> _firstMeanings(IncantationCodebook book, int n) => [
      for (final key in book.orderedKeys.take(n))
        (book.lookup(key) as IncantationEffect).kind,
    ];

